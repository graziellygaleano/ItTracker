-- Exemplo de tabela para usar com js/supabase-exemplo.js.
create table if not exists public.equipamentos (
  id bigint generated by default as identity primary key,
  nome text not null,
  patrimonio text not null unique,
  estado text not null default 'disponível',
  criado_em timestamptz not null default now()
);

alter table public.equipamentos enable row level security;

-- A consulta do exemplo fica disponível sem login.
create policy "Leitura pública dos equipamentos"
  on public.equipamentos for select
  to anon, authenticated
  using (true);

-- O cadastro só funciona para sessões criadas pelo Supabase Auth.
-- O login atual deste projeto usa localStorage e não autentica no Supabase.
create policy "Usuários autenticados podem cadastrar equipamentos"
  on public.equipamentos for insert
  to authenticated
  with check (true);
